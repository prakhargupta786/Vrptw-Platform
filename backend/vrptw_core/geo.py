from math import asin, cos, radians, sin, sqrt

EARTH_RADIUS_KM = 6371.0088


def haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    dlat, dlon = radians(lat2 - lat1), radians(lon2 - lon1)
    a = sin(dlat / 2) ** 2 + cos(radians(lat1)) * cos(radians(lat2)) * sin(dlon / 2) ** 2
    return 2 * EARTH_RADIUS_KM * asin(sqrt(a))


def travel_minutes(distance_km: float, speed_kmh: float, traffic_factor: float) -> float:
    """PDF: time = distance / speed x traffic factor."""
    return distance_km / speed_kmh * 60 * traffic_factor


def in_region(lon: float, lat: float, polygon: tuple[tuple[float, float], ...]) -> bool:
    """Ray-casting point-in-polygon; polygon given as (lon, lat) vertices."""
    inside = False
    n = len(polygon)
    for i in range(n):
        x1, y1 = polygon[i]
        x2, y2 = polygon[(i + 1) % n]
        if (y1 > lat) != (y2 > lat) and lon < (x2 - x1) * (lat - y1) / (y2 - y1) + x1:
            inside = not inside
    return inside
